#!/usr/bin/env python3
"""설정 검색 색인을 페이지 코드에서 만든다 / Builds the settings search index from the page sources.

build.sh가 빌드 전에 실행한다. 페이지의 줄 이름·보조 설명·구역 이름(T("한국어", "English"))을 읽어
Sources/DynamicMacNotch/Settings/SettingsIndex+Generated.swift를 쓴다. 화면 글을 고치면 색인도 저절로 따라간다.
Run by build.sh before building. Do not edit the generated file by hand.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SET = os.path.join(ROOT, "Sources", "DynamicMacNotch", "Settings")
OUT = os.path.join(SET, "SettingsIndex+Generated.swift")

S = r'"((?:[^"\\]|\\.)*)"'
T = r'T\(\s*' + S + r',\s*' + S + r'\s*\)'


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


# 페이지 이름·설명 (SettingsPage.swift)
page_src = read(os.path.join(SET, "SettingsPage.swift"))
def block(name):
    i = page_src.index("var %s: String {" % name)
    j = page_src.index("\n    }\n", i)
    return page_src[i:j]
def cases(text):
    out = {}
    for m in re.finditer(r'case \.(\w+): return (?:' + T + '|' + S + ')', text):
        page = m.group(1)
        if m.group(2) is not None:
            out[page] = (m.group(2), m.group(3))
        else:
            out[page] = (m.group(4), m.group(4))
    return out
page_titles = cases(block("title"))
page_summaries = cases(block("summary"))
page_order = list(page_titles)

# 구역 이름 상수 (SectionTitle)
comp = read(os.path.join(SET, "SettingsComponents.swift"))
section_names = {m.group(1): (m.group(2), m.group(3))
                 for m in re.finditer(r'static var (\w+): String \{ ' + T + r' \}', comp)}

# 페이지 구조체 → 페이지 (SettingsView.content)
view = read(os.path.join(SET, "SettingsView.swift"))
struct_page = {}
for m in re.finditer(r'case \.(\w+): (\w+)\s*[({]', view):
    struct_page.setdefault(m.group(2), m.group(1))

# 줄을 만드는 부품과 그 부품이 정하는 기본 이름
DEFAULT_TITLE = {
    "AlertStylePicker": ("표시 형태", "Style"),
    "AlertDurationMenu": ("표시 시간", "Duration"),
    "ProgressStylePicker": ("진행률 표시", "Progress"),
}
ROW = re.compile(
    r'\b(Toggle|HomePageToggle|Choice|ListChoice|ValueMenu|ValueSlider|ListField|FolderSetting|LabeledContent|DisclosureGroup)'
    r'\((?:[^()]*?title:\s*)?\s*' + T + r'(?:\s*,\s*detail:\s*' + T + r')?')
FIXED = re.compile(r'\b(AlertStylePicker|AlertDurationMenu|ProgressStylePicker)\((?:title:\s*' + T + r'\s*,\s*)?selection:\s*\$settings\.(\w+)')
SECTION = re.compile(r'SettingsSection\(\s*(?:SectionTitle\.(\w+)|' + T + r')')
KEY = re.compile(r'\$settings\.(\w+)|[^.\w]settings\.(\w+)(?:\[[^\]]*\])?\s*=[^=]|key:\s*"(\w+)"')
HOME_KEY = {"chat": "chatEnabled", "usage": "monitorContent", "resource": "monitorContent"}   # HomePageToggle(key:)이 바꾸는 설정


def clean(s):
    return s.replace('\\"', '"')


entries = []
pages_dir = os.path.join(SET, "Pages")
for name in sorted(os.listdir(pages_dir)):
    if not name.endswith(".swift"):
        continue
    src = read(os.path.join(pages_dir, name))
    structs = [(m.start(), m.group(1)) for m in re.finditer(r'(?m)^(?:private )?struct (\w+)', src)]
    sections = []
    for m in SECTION.finditer(src):
        title = section_names.get(m.group(1)) if m.group(1) else (m.group(2), m.group(3))
        sections.append((m.start(), title))

    def context(pos):
        struct = max((s for s in structs if s[0] < pos), default=(0, None))
        sec = max((s for s in sections if struct[0] < s[0] < pos), default=(0, None))
        return struct[1], sec[1]

    def add(pos, title, detail, statement):
        struct, section = context(pos)
        page = struct_page.get(struct)
        if not page or "\\(" in title[0]:
            return   # 페이지가 아닌 부품, 실행 중에 정해지는 이름
        if section and "\\(" in section[0]:
            section = None   # 실행 중에 정해지는 구역 이름은 빼고 줄만 남긴다
        if detail and "\\(" in detail[0]:
            detail = None
        keys = []
        for k in KEY.finditer(statement):
            key = k.group(1) or k.group(2) or (HOME_KEY.get(k.group(3), "homeDisabled") if k.group(3) else None)
            if key and key not in keys:
                keys.append(key)
        entries.append(dict(page=page, section=section, title=title, detail=detail, keys=keys))

    for m in ROW.finditer(src):
        end = src.find("\n", m.end())
        statement = src[m.start():end]
        if not KEY.search(statement):   # 이 줄에 없으면 이어지는 다음 줄까지
            statement = src[m.start():src.find("\n", end + 1)]
        detail = (m.group(4), m.group(5)) if m.group(4) is not None else None
        add(m.start(), (m.group(2), m.group(3)), detail, statement)
    for m in FIXED.finditer(src):
        title = (m.group(2), m.group(3)) if m.group(2) is not None else DEFAULT_TITLE[m.group(1)]
        add(m.start(), title, None, m.group(0))

def swift(s):
    return '"' + s + '"'

lines = [
    "// 자동 생성 — scripts/gen-settings-index.py가 빌드할 때마다 다시 만든다. 손으로 고치지 않는다.",
    "// Generated by scripts/gen-settings-index.py on every build. Do not edit.",
    "",
    "extension SettingsIndex {",
    "    static let pages: [SettingsEntry] = [",
]
for p in page_order:
    t = page_titles[p]
    s = page_summaries.get(p, ("", ""))
    lines.append("        SettingsEntry(page: .%s, section: nil, title: (%s, %s), detail: (%s, %s), keys: [], isPage: true),"
                 % (p, swift(t[0]), swift(t[1]), swift(s[0]), swift(s[1])))
lines += ["    ]", "", "    static let rows: [SettingsEntry] = ["]
merged = {}
for e in entries:   # 같은 페이지의 같은 이름(조건에 따라 바뀌는 줄)은 하나로, 설정 이름은 합친다
    ident = (e["page"], e["title"][0])
    if ident in merged:
        merged[ident]["keys"] += [k for k in e["keys"] if k not in merged[ident]["keys"]]
    else:
        merged[ident] = e
seen = merged
rows = []
for e in sorted(merged.values(), key=lambda e: page_order.index(e["page"])):
    sec = "(%s, %s)" % (swift(e["section"][0]), swift(e["section"][1])) if e["section"] else "nil"
    det = "(%s, %s)" % (swift(e["detail"][0]), swift(e["detail"][1])) if e["detail"] else "nil"
    keys = "[" + ", ".join(swift(k) for k in e["keys"]) + "]"
    rows.append("        SettingsEntry(page: .%s, section: %s, title: (%s, %s), detail: %s, keys: %s)"
                % (e["page"], sec, swift(e["title"][0]), swift(e["title"][1]), det, keys))
lines.append(",\n".join(rows) + ",")
lines += ["    ]", "}", ""]
text = "\n".join(lines)

if os.path.exists(OUT) and read(OUT) == text:
    sys.exit(0)
with open(OUT, "w", encoding="utf-8") as f:
    f.write(text)
print("settings index: %d pages, %d rows" % (len(page_order), len(seen)))
